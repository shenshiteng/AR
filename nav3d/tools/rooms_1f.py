IMG = os.path.join(R, "docs", "img", "1f_deskew.png")

_m = None


def m():
    global _m
    if _m is None:
        im = Image.open(IMG).convert("RGB")
        a = np.asarray(im).astype(np.int16)
        r, g, b = a[:, :, 0], a[:, :, 1], a[:, :, 2]
        x = (r - np.maximum(g, b)) > 12
        x[:280, :] = False
        x[1760:, :] = False
        x[:, :120] = False
        x[:, 1670:] = False
        _m = x
    return _m


def cov_h(y, x1, x2, band=3):
    s = m()[y - band:y + band + 1, x1:x2].any(axis=0)
    return s.sum() / float(x2 - x1)


def cov_v(x, y1, y2, band=3):
    s = m()[y1:y2, x - band:x + band + 1].any(axis=1)
    return s.sum() / float(y2 - y1)


def check(name, x1, y1, x2, y2, need=0.50):
    c = [cov_h(y1, x1, x2), cov_h(y2, x1, x2),
         cov_v(x1, y1, y2), cov_v(x2, y1, y2)]
    bad = [k for k, v in zip("上下左右", c) if v < need]
    print("%-16s x%-4d-%-4d y%-4d-%-4d %4dx%-4d  上%3.0f%% 下%3.0f%% 左%3.0f%% 右%3.0f%%  %s" % (
        name, x1, x2, y1, y2, x2 - x1, y2 - y1,
        c[0] * 100, c[1] * 100, c[2] * 100, c[3] * 100,
        "OK" if not bad else "缺" + "".join(bad)))
    return not bad


