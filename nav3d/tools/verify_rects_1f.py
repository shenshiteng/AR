"""1F 逐房间验证：给定一个候选矩形，检查它的四条边是否真的贴着墙。

这是"人工给矩形 + 机器验证边界"的组合：比全自动分割可靠，
因为扫描件的墙是断的、有文字干扰，全自动必然出错，但"这一条边是不是墙"可以精确判断。
"""
import os

import numpy as np
from PIL import Image

R = r"C:\Users\35391\Desktop\python\实验室定位"
IMG = os.path.join(R, "docs", "img", "1f_deskew.png")

_m = None


def m():
    global _m
    if _m is None:
        im = Image.open(IMG).convert("RGB")
        a = np.asarray(im).astype(np.int16)
        r, g, b = a[:, :, 0], a[:, :, 1], a[:, :, 2]
        x = (r - np.maximum(g, b)) > 12
        x[:280, :] = False
        x[1760:, :] = False
        x[:, :120] = False
        x[:, 1670:] = False
        _m = x
    return _m


def cover_h(y, x1, x2, band=3):
    """该水平线上，x1..x2 范围内有红像素的比例（band 内任一行有红算有）。"""
    mm = m()
    seg = mm[y - band:y + band + 1, x1:x2].any(axis=0)
    return seg.sum() / float(x2 - x1)


def cover_v(x, y1, y2, band=3):
    mm = m()
    seg = mm[y1:y2, x - band:x + band + 1].any(axis=1)
    return seg.sum() / float(y2 - y1)


def check(name, x1, y1, x2, y2, need=0.55):
    """检查四条边。边长越长，允许的覆盖率越低（因为门洞会占掉一段）。"""
    sides = {
        "上": (cover_h(y1, x1, x2), x2 - x1),
        "下": (cover_h(y2, x1, x2), x2 - x1),
        "左": (cover_v(x1, y1, y2), y2 - y1),
        "右": (cover_v(x2, y1, y2), y2 - y1),
    }
    bad = []
    for k, (c, ln) in sides.items():
        if c < need:
            bad.append("%s边%.0f%%" % (k, c * 100))
    w, h = x2 - x1, y2 - y1
    status = "OK " if not bad else "差距"
    print("%-14s x%-4d-%-4d y%-4d-%-4d  %4dx%-4d  %s %s" % (
        name, x1, x2, y1, y2, w, h, status,
        "上%.0f%% 下%.0f%% 左%.0f%% 右%.0f%%" % (
            sides["上"][0] * 100, sides["下"][0] * 100,
            sides["左"][0] * 100, sides["右"][0] * 100)))
    return not bad


